// the structure of SRS for ZK Samaritan multilinear PCS, consists of [g, g\tau, g\tau^2,...] and [h, h\tau, h\tau^2,...] and g\xi and h\xi, where g and h are random generators of G1 and G2 and xi is a random F element
pub struct ZKSamaritanMLPCS_SRS<E: Pairing> {
    pub(crate) powers_of_g: Vec<E::G1Affine>,
    pub(crate) powers_of_h: Vec<E::G2Affine>,
    pub(crate) xi_g1: E::G1Affine,
    pub(crate) xi_g2: E::G2Affine
}

// the structure to hold the proof single evaluation of univariate polynomials using hiding KZG10
pub struct HidingKZG10EvalProof<E: Pairing> {
    proof_1: E::G1Affine,
    proof_2: E::G1Affine,
}

// the structure of the proof generated by SamaritanMLPCS to prove the evaluation at a point
pub struct ZKSamaritanMLPCSEvalProof<E: Pairing> {
    v_hat_commit: Commitment<E>,
    c_hat_commit: Commitment<E>,
    d_hat_commit: Commitment<E>,
    gamma_commit: Commitment<E>,
    zeta: E::ScalarField,
    eta: E::ScalarField,
    p_hat_commit: Commitment<E>,
    b_hat_commit: Commitment<E>,
    u_hat_commit: Commitment<E>,
    t_hat_commit: Commitment<E>,
    s_hat_commit: Commitment<E>,
    q_eval_proof: HidingKZG10EvalProof<E>,
    deg_check_randomness: E::G1Affine,
    sigma_protocol_proof: SigmaProtocolProof<E>
}

// the structure of the proof generated by SamaritanMLPCS to prove the evaluation at a point
